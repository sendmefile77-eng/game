    fun chapter(era: TechnologyEra): EraChapter = chapters.getValue(era)

    fun eraFromDecision(decision: ChronicleDecision): TechnologyEra? = TechnologyEra.entries.firstOrNull { era ->
        val prefix = "era-${era.name.lowercase()}-"
        decision.options.any { it.id.startsWith(prefix) }
    }

    fun turnIntro(era: TechnologyEra, civilizationName: String): String {
        val chapter = chapter(era)
        return buildString {
            append(chapter.opening)
            append("\n\n")
            append("Для ").append(civilizationName).append(" зараз важливо інше: ")
            append(chapter.danger.replaceFirstChar { it.lowercase() })
            append(" ")
            append(chapter.horizon)
        }
    }

    fun centuryOutcome(report: GameplayTurnReport): String {
        if (!report.survived) {
            return "Століття закінчилося не реформою і не перемогою, а зникненням держави. Її поселення, люди й пам’ять тепер існуватимуть лише всередині чужої історії."
        }
        val population = when {
            report.populationDelta > 50_000 -> "населення різко зросло"
            report.populationDelta > 0 -> "людей стало більше"
            report.populationDelta < -10_000 -> "держава пережила важкі людські втрати"
            report.populationDelta < 0 -> "населення скоротилося"
            else -> "чисельність майже не змінилася"
        }
        val order = when {
            report.stabilityDelta >= 0.08 -> "влада стала помітно міцнішою"
            report.stabilityDelta <= -0.08 -> "внутрішній порядок серйозно похитнувся"
            else -> "політичний баланс загалом утримався"
        }
        val progress = when {
            report.technologyDelta >= 0.08 -> "технологічний уклад змінився швидше, ніж зазвичай змінюється одне покоління"
            report.technologyDelta > 0.01 -> "знання й виробництво повільно просунулися вперед"
            else -> "великих технологічних переломів не сталося"
        }
        val war = when {
            report.warsAfter > report.warsBefore -> "До кінця століття фронтів стало більше."
            report.warsAfter < report.warsBefore -> "Частину воєн вдалося залишити в минулому."
            report.warsAfter > 0 -> "Війна так і залишилася частиною повсякденної політики."
            else -> "Держава завершила століття без активної війни."
        }
        return "Минуло сто років: $population, $order, а $progress. $war"
    }
