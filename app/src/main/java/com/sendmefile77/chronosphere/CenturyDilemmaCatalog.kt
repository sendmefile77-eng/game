    private fun stableIndex(key: String, size: Int): Int {
        var hash = 0x811C9DC5.toInt()
        key.forEach { char -> hash = (hash xor char.code) * 16777619 }
        return (hash and Int.MAX_VALUE) % size.coerceAtLeast(1)
    }
