/**
 * Guarantees that a quiet century still asks the player a concrete question.
 * Real simulation events always take priority; these dilemmas are only used when history itself has
 * not already produced an unresolved fork.
 */
internal object CenturyDilemmaCatalog {
    private data class OptionSpec(
        val slug: String,
        val title: String,
        val effect: String,
        val risk: String,
        val kind: InterventionKind,
        val strength: Double,
    )

    private data class DilemmaSpec(
        val slug: String,
        val title: String,
        val prompt: String,
        val options: List<OptionSpec>,
    )

    fun fromEraDecision(eraDecision: ChronicleDecision): ChronicleDecision? {
        val era = EraExperience.eraFromDecision(eraDecision) ?: return null
        val targetCivilizationId = eraDecision.options.firstOrNull()?.targetCivilizationId ?: return null
        val pool = dilemmas.getValue(era)
        val spec = pool[stableIndex(eraDecision.eventId, pool.size)]
        val source = "${eraDecision.eventId}-dilemma-${spec.slug}"
        return ChronicleDecision(
            eventId = source,
            titleUk = spec.title,
            promptUk = spec.prompt,
            options = spec.options.map { option ->
                ChronicleDecisionOption(
                    id = "dilemma-${era.name.lowercase()}-${spec.slug}-${option.slug}",
                    sourceEventId = source,
                    titleUk = option.title,
                    effectUk = option.effect,
                    riskUk = option.risk,
                    kind = option.kind,
                    targetCivilizationId = targetCivilizationId,
                    strength = option.strength,
                )
            },
        )
    }

    private fun o(
        slug: String,
        title: String,
        effect: String,
        risk: String,
        kind: InterventionKind,
        strength: Double,
    ) = OptionSpec(slug, title, effect, risk, kind, strength)

    private fun d(slug: String, title: String, prompt: String, vararg options: OptionSpec) =
        DilemmaSpec(slug, title, prompt, options.toList())

